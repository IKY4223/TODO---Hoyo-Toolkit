"""Rebuild frontend/src/wishes/genshin-banners.ts from paimon.moe's list of Genshin banners.

paimon.moe (github.com/MadeBaruna/paimon-moe, MIT licence, copyright (c) 2021 Made Baruna) keeps
every character event banner with its dates and featured characters in src/data/banners.js.
The file is a JavaScript module: it is read as text here, never run.

Run after each banner phase: uv run python scripts/sync_banners.py
"""

import json
import re
from pathlib import Path
from typing import Any
from urllib.request import urlopen

SOURCE = "https://raw.githubusercontent.com/MadeBaruna/paimon-moe/main/src/data/banners.js"
GAMEDATA = Path(__file__).parent.parent / "app" / "showcase" / "gamedata.json"
TARGET = Path(__file__).parents[2] / "frontend" / "src" / "wishes" / "genshin-banners.ts"

COMMENT = re.compile(r"^\s*//.*$", re.MULTILINE)
# One banner: the list holds no braces inside an entry.
ENTRY = re.compile(r"\{(.*?)\}", re.DOTALL)
# A date as the list writes it: accepts "2020-09-28 00:00:00", rejects "2020-9-28".
# https://regex101.com/?flavor=python&regex=%5Cd%7B4%7D-%5Cd%7B2%7D-%5Cd%7B2%7D+%5Cd%7B2%7D%3A%5Cd%7B2%7D%3A%5Cd%7B2%7D&testString=2020-09-28+00%3A00%3A00
DATE = r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}"


def _key(name: str) -> str:
    """paimon.moe's key for a character: "Hu Tao" is "hu_tao"."""
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")


def character_banners(source: str, names: dict[str, str]) -> list[dict[str, Any]]:
    """Each character event banner: its dates and its featured 5-stars by English name.

    Dates are in the Asia server's time (UTC+8) where `startAsia` or `endAsia` says so, and in
    each server's own time otherwise, as paimon.moe's src/functions/wish.js reads them.
    """
    text = COMMENT.sub("", source)
    section = text[text.index("characters: [") : text.index("weapons: [")]
    banners = []
    for entry in ENTRY.findall(section):
        start = re.search(rf"start: '({DATE})'", entry)
        end = re.search(rf"end: '({DATE})'", entry)
        featured = re.search(r"featured: \[([^\]]*)\]", entry)
        if not (start and end and featured):
            raise ValueError(f"a banner without dates or featured characters: {entry[:60]}")
        keys = re.findall(r"'([^']+)'", featured[1])
        if unknown := [key for key in keys if key not in names]:
            raise ValueError(f"featured characters the game data does not know: {unknown}")
        banners.append(
            {
                "start": start[1],
                "end": end[1],
                "startAsia": "timezoneDependent: true" in entry,
                "endAsia": "timezoneDependentEnd: true" in entry,
                "featured": [names[key] for key in keys],
            }
        )
    return banners


def main() -> None:
    characters = json.loads(GAMEDATA.read_text())["characters"]
    names = {_key(data["name"]): data["name"] for data in characters.values()}
    with urlopen(SOURCE, timeout=60) as response:
        banners = character_banners(response.read().decode(), names)
    lines = [
        "// Generated by backend/scripts/sync_banners.py from paimon.moe's banners. Do not edit.",
        "",
        "export interface GenshinBanner {",
        "  readonly start: string",
        "  readonly end: string",
        "  /** The time is the Asia server's (UTC+8), not each server's own. */",
        "  readonly startAsia: boolean",
        "  readonly endAsia: boolean",
        "  /** English names, as the wish history gives them. */",
        "  readonly featured: readonly string[]",
        "}",
        "",
        "export const CHARACTER_BANNERS: readonly GenshinBanner[] = [",
        *(f"  {json.dumps(banner, ensure_ascii=False)}," for banner in banners),
        "]",
        "",
        "/** Every playable character's English name, standard ones included. */",
        "export const CHARACTER_NAMES: ReadonlySet<string> = new Set([",
        *(f"  {json.dumps(name)}," for name in sorted(set(names.values()))),
        "])",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"{len(banners)} character banners")


if __name__ == "__main__":
    main()
