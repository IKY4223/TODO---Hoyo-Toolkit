"""Names, talent ids and talent tables the Enka response only refers to by id.

gamedata.json and talents.json are generated by scripts/sync_gamedata.py.
"""

from pathlib import Path
from typing import Literal

from pydantic import BaseModel, TypeAdapter

from app.showcase.models import Element, StatKey

HERE = Path(__file__).parent


class CharacterData(BaseModel):
    name: str
    element: Element | None
    icon: str
    talents: list[tuple[int, int]]  # (talent id, id constellations boost it by), in display order


class GameData(BaseModel):
    characters: dict[str, CharacterData]
    weapons: dict[str, str]
    sets: dict[str, str]


class TalentName(BaseModel):
    en: str
    ru: str


class TalentTerm(BaseModel):
    stat: Literal[StatKey.ATK, StatKey.HP, StatKey.DEF, StatKey.ELEMENTAL_MASTERY]
    values: list[float]  # the multiplier at talent level 1, 2, ...: 0.457 is 45.7%


class TalentHit(BaseModel):
    name: TalentName
    terms: list[TalentTerm]  # one per stat the hit scales with


GAMEDATA = GameData.model_validate_json((HERE / "gamedata.json").read_bytes())
# A talent level group id, as GameData lists it, -> the hits its table describes.
TALENTS = TypeAdapter(dict[str, list[TalentHit]]).validate_json(
    (HERE / "talents.json").read_bytes()
)
